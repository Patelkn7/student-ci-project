def add_numbers(a, b):
    return a + b


def subtract_numbers(a, b):
    return a - b

def multiply_numbers(a, b):
    return a * b


if __name__ == "__main__":
    print("Application started")
    print("2 + 3 =", add_numbers(2, 3))
    print("5 - 2 =", subtract_numbers(5, 2))
    print("4 * 6 =", multiply_numbers(4, 6))